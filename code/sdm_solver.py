"""
2-DOF milling regenerative chatter: stability lobe diagrams (SLD)
via the (updated) semi-discretization method (SDM).

Model (Insperger & Stepan 2004; Ding et al. 2010 conventions):
    M q'' + C q' + K q = a_p * K_t * A(t) * [q(t) - q(t - tau)]
with q in R^2, M = m_t I, C = 2*zeta*wn*m_t I, K = wn^2 m_t I,
tau = 2*pi/(N*Omega_spindle), and A(t) the periodic directional matrix.

Stability: spectral radius of the one-period transition matrix < 1.

Authorship: generated by Codex (window 1) as part of an AI-conducted study.
"""

from __future__ import annotations

import itertools
from dataclasses import dataclass, asdict

import numpy as np
from scipy.linalg import expm
from scipy.sparse import lil_matrix, csr_matrix
from scipy.sparse.linalg import eigs


@dataclass(frozen=True)
class MillingParams:
    """Baseline: Insperger & Stepan (2004) 2-DOF benchmark."""
    N: int = 2                 # number of teeth
    fn: float = 922.0          # natural frequency [Hz]
    zeta: float = 0.011        # damping ratio
    mt: float = 0.03993        # modal mass [kg]
    Kt: float = 6.0e8          # tangential cutting coefficient [N/m^2]
    Kn: float = 2.0e8          # normal cutting coefficient [N/m^2]
    ad: int = -1               # -1 down milling, +1 up milling
    aD: float = 0.5            # radial immersion ratio a/D

    @property
    def wn(self) -> float:
        return 2.0 * np.pi * self.fn

    @property
    def r(self) -> float:
        return self.Kn / self.Kt

    @property
    def phi_st(self) -> float:
        if self.ad < 0:                      # down milling
            return 0.0
        return np.arccos(2.0 * self.aD - 1.0)   # up milling

    @property
    def phi_ex(self) -> float:
        if self.ad < 0:                      # down milling
            return np.arccos(1.0 - 2.0 * self.aD)
        return np.pi


def direction_coeffs(phi: float, p: MillingParams) -> np.ndarray:
    """2x2 directional matrix A(phi) for one tooth at angle phi.

    g(phi) = 1 while phi in [phi_st, phi_ex] (entry/exit per immersion).
    Formula follows the standard 2-DOF milling model with r = Kn/Kt.
    """
    g = 1.0 if p.phi_st <= phi <= p.phi_ex else 0.0
    if g == 0.0:
        return np.zeros((2, 2))
    s2 = np.sin(2.0 * phi)
    c2 = np.cos(2.0 * phi)
    r = p.r
    a = np.array([
        [-s2 - r * (1.0 - c2),
         -(1.0 + c2) + r * s2],
        [(1.0 - c2) - r * s2,
         s2 - r * (1.0 + c2)],
    ]) / 2.0
    return a


def direction_matrix(time: float, n_rpm: float, p: MillingParams) -> np.ndarray:
    """Summed directional matrix A(t) over all teeth at time t."""
    omega_s = 2.0 * np.pi * n_rpm / 60.0          # spindle angular speed
    pitch = 2.0 * np.pi / p.N
    A = np.zeros((2, 2))
    for j in range(p.N):
        phi = np.mod(omega_s * time + j * pitch, 2.0 * np.pi)
        A += direction_coeffs(phi, p)
    return A


def _L_R_matrices(A: np.ndarray, a_p: float, p: MillingParams) -> tuple[np.ndarray, np.ndarray]:
    """State-space matrices: L (4x4) for u=[q;q'], R (4x2) acting on delayed q."""
    wn = p.wn
    kappa = a_p * p.Kt / p.mt
    L = np.zeros((4, 4))
    L[0, 2] = 1.0
    L[1, 3] = 1.0
    # q'' = -2 zeta wn q' - wn^2 q + kappa A (q - q_delay)
    #   => coefficient of current q is -wn^2 I + kappa A
    #   => coefficient of delayed q is -kappa A
    L[2:4, :2] = -wn * wn * np.eye(2) + kappa * A
    L[2:4, 2:] = -2.0 * p.zeta * wn * np.eye(2)
    R = np.zeros((4, 2))
    R[2:, :] = -kappa * A
    return L, R


def _interval_flow(L: np.ndarray, R: np.ndarray, dt: float) -> tuple[np.ndarray, np.ndarray]:
    """Phi = exp(L dt); Psi = int_0^dt exp(L s) ds * R, computed stably
    with the block-exponential trick: exp(dt * [[L, R],[0,0]]) = [[Phi, Psi],[0, I]].
    """
    M = np.zeros((6, 6))
    M[:4, :4] = L
    M[:4, 4:] = R
    E = expm(M * dt)
    return E[:4, :4].copy(), E[:4, 4:].copy()


def _interval_flow_linear(L: np.ndarray, R: np.ndarray,
                          dt: float) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """First-order (linear-in-delay) SDM interval matrices.

    On interval i, q(t-tau) is approximated by the linear interpolation
        q(t_i + s - tau) ~= (1 - s/dt) q_{i-m} + (s/dt) q_{i-m+1},
    so the interval flow reads
        u_{i+1} = Phi u_i + Psi0 q_{i-m} + Psi1 q_{i-m+1}.

    Block-exponential identity (8x8):
        exp(dt * [[L, R, 0],[0, 0, I],[0, 0, 0]]) = [[Phi, Psi, Psi1*dt],
                                                     [0,   I,   I     ],
                                                     [0,   0,   I     ]]
    with Psi = Psi0 + Psi1 = int_0^dt exp(L s) ds * R.

    The top-right block is int_0^dt (dt-s) exp(L s) ds * R = dt * Psi0
    (verified against entrywise Gauss quadrature), hence:
        Psi0 = E[:4, 6:8] / dt,
        Psi1 = Psi - Psi0.
    """
    M = np.zeros((8, 8))
    M[:4, :4] = L
    M[:4, 4:6] = R
    M[4:6, 6:8] = np.eye(2)
    E = expm(M * dt)
    Phi = E[:4, :4].copy()
    Psi = E[:4, 4:6].copy()
    Psi0 = E[:4, 6:8].copy() / dt
    Psi1 = Psi - Psi0
    return Phi, Psi0, Psi1


def one_period_transition(n_rpm: float, a_p: float, p: MillingParams,
                          m: int = 40) -> np.ndarray:
    """Build the (2m+4)-dimensional one-period transition matrix.

    State layout:
        z_i = [u_i (4), q_{i-1} (2), q_{i-2} (2), ..., q_{i-m} (2)]
    Only delayed positions are stored (the DDE delay acts on q only),
    giving dimension 4 + 2m.
    """
    omega_s = 2.0 * np.pi * n_rpm / 60.0
    tau = 2.0 * np.pi / (p.N * omega_s)
    dt = tau / m

    dim = 4 + 2 * m
    D = np.eye(dim)
    # z_{i+1} = D_i z_i  =>  z_m = D_{m-1} ... D_0 z_0.
    # Iterate intervals in reverse time and accumulate D = D @ Di so that the
    # last-interval matrix ends up leftmost.
    for i in range(m - 1, -1, -1):
        t_mid = (i + 0.5) * dt
        A = direction_matrix(t_mid, n_rpm, p)
        L, R = _L_R_matrices(A, a_p, p)
        Phi, Psi0, Psi1 = _interval_flow_linear(L, R, dt)
        Di = np.zeros((dim, dim))
        Di[:4, :4] = Phi
        # delayed positions: q_{i-m+1} (block index m-1 in history) and q_{i-m} (block m)
        if m == 1:
            # q_{i-m+1} = q_i is the position part of u_i
            Di[:4, :2] += Psi1
            Di[:4, 4:6] = Psi0
        else:
            Di[:4, 4 + 2 * (m - 2):4 + 2 * (m - 1)] = Psi1
            Di[:4, 4 + 2 * (m - 1):4 + 2 * m] = Psi0
        # shift history: new q_i from u_i
        Di[4:6, :2] = np.eye(2)
        # shift older history blocks
        for k in range(1, m):
            Di[4 + 2 * k:6 + 2 * k, 4 + 2 * (k - 1):6 + 2 * (k - 1)] = np.eye(2)
        D = D @ Di
    return D


def floquet_radius(n_rpm: float, a_p: float, p: MillingParams,
                   m: int = 40) -> float:
    """Spectral radius of the one-period transition matrix."""
    D = one_period_transition(n_rpm, a_p, p, m=m)
    return float(np.max(np.abs(np.linalg.eigvals(D))))


def floquet_radius_sparse(n_rpm: float, a_p: float, p: MillingParams,
                          m: int = 40, k: int = 6) -> float:
    """Sparse variant (faster for large m); k dominates eigs count."""
    omega_s = 2.0 * np.pi * n_rpm / 60.0
    tau = 2.0 * np.pi / (p.N * omega_s)
    dt = tau / m
    dim = 4 + 2 * m
    D = csr_matrix(np.eye(dim))
    for i in range(m - 1, -1, -1):
        t_mid = (i + 0.5) * dt
        A = direction_matrix(t_mid, n_rpm, p)
        L, R = _L_R_matrices(A, a_p, p)
        Phi, Psi0, Psi1 = _interval_flow_linear(L, R, dt)
        Di = lil_matrix((dim, dim))
        Di[:4, :4] = Phi
        if m == 1:
            Di[:4, :2] += Psi1
            Di[:4, 4:6] = Psi0
        else:
            Di[:4, 4 + 2 * (m - 2):4 + 2 * (m - 1)] = Psi1
            Di[:4, 4 + 2 * (m - 1):4 + 2 * m] = Psi0
        Di[4:6, :2] = np.eye(2)
        for k in range(1, m):
            Di[4 + 2 * k:6 + 2 * k, 4 + 2 * (k - 1):6 + 2 * (k - 1)] = np.eye(2)
        D = D @ Di.tocsr()
    vals = eigs(D, k=min(k, dim - 2), return_eigenvectors=False, which="LM")
    return float(np.max(np.abs(vals)))


def compute_sld(n_rpms: np.ndarray, a_ps: np.ndarray, p: MillingParams,
                m: int = 40, sparse: bool = False, progress: bool = True) -> np.ndarray:
    """SLD matrix of spectral radii: shape (len(a_ps), len(n_rpms)).
    Rows = axial depth, columns = spindle speed.
    """
    out = np.empty((len(a_ps), len(n_rpms)))
    fn_rad = (floquet_radius_sparse if sparse else floquet_radius)
    total = len(a_ps) * len(n_rpms)
    count = 0
    for i, a_p in enumerate(a_ps):
        for j, n in enumerate(n_rpms):
            out[i, j] = fn_rad(n, a_p, p, m=m)
            count += 1
            if progress and count % 500 == 0:
                print(f"  SDM {count}/{total}")
    return out


def stable_mask(radii: np.ndarray) -> np.ndarray:
    return radii < 1.0


